import { siteConfig } from "./site.config";

const { legal, contacts, analytics, brand } = siteConfig;
const metrika = Boolean(analytics.yandexMetrikaId);

export function operatorLine(): string {
  switch (legal.form) {
    case "ip":
      return `ИП ${legal.fullName}, ИНН ${legal.inn}${legal.ogrn ? `, ОГРНИП ${legal.ogrn}` : ""}`;
    case "ooo":
      return `${legal.fullName}, ИНН ${legal.inn}${legal.ogrn ? `, ОГРН ${legal.ogrn}` : ""}`;
    default:
      return `${legal.fullName}, плательщик налога на профессиональный доход (самозанятый), ИНН ${legal.inn}`;
  }
}

const Operator = () => (
  <p>
    <b>Оператор:</b> {operatorLine()}. Адрес для обращений: {legal.address}. Эл. почта:{" "}
    <a href={`mailto:${legal.privacyEmail}`}>{legal.privacyEmail}</a>, телефон: {contacts.phone}.
  </p>
);

